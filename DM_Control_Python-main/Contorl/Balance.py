from __future__ import annotations

import runpy
from dataclasses import dataclass
from pathlib import Path
import time

# Runtime-tunable parameters. Edit these values and save Balance.py while main.py is running.
BALANCE_PITCH_KP = 0.1
BALANCE_PITCH_KI = 0.0
BALANCE_PITCH_KD = 0.0012

# Wheel velocity feedback gain, Nm/(rad/s). Torque uses -Kv * wheel_velocity.
BALANCE_WHEEL_KV = 0.005

BALANCE_MOTOR3_KD = 0.005
BALANCE_MOTOR4_KD = 0.075

@dataclass
class BalanceConfig:
    """Parameters used by the wheel-leg balance controller."""

    # Pitch target in deg.
    target_pitch_deg: float = 7.5

    # Roll target in deg.
    target_roll_deg: float = -1.0

    # Joint target angle in rad.
    target_q_rad: float = -0.1

    # Pitch proportional gain, Nm/deg.
    pitch_torque_kp: float = BALANCE_PITCH_KP

    # Pitch integral gain, Nm/(deg*s).
    pitch_torque_ki: float = BALANCE_PITCH_KI

    # Pitch derivative gain, Nm/(deg/s).
    pitch_rate_torque_kd: float = BALANCE_PITCH_KD

    # Wheel velocity feedback gain, Nm/(rad/s).
    wheel_velocity_kv: float = BALANCE_WHEEL_KV

    # Integral clamp in deg*s to avoid windup.
    pitch_integral_limit_deg_s: float = 10.0

    # Wheel torque clamp in Nm.
    max_wheel_torque: float = 0.22


@dataclass
class BalanceOutput:
    """Output generated by the balance controller."""

    # Pitch error in deg, defined as pitch - target_pitch.
    pitch_error_deg: float

    # Pitch integral in deg*s.
    pitch_integral_deg_s: float

    # Roll error in deg, defined as roll - target_roll.
    roll_error_deg: float

    # Joint target angle in rad.
    target_q_rad: float

    # Torque command for motor 0x03.
    motor3_tau: float

    # Torque command for motor 0x04, always opposite to 0x03.
    motor4_tau: float


@dataclass(frozen=True)
class RuntimeBalanceGains:
    """Runtime-tunable balance parameters loaded from Balance.py."""

    # Pitch proportional gain.
    pitch_kp: float

    # Pitch integral gain.
    pitch_ki: float

    # Pitch derivative gain.
    pitch_kd: float

    # Wheel velocity feedback gain.
    wheel_kv: float

    # MIT velocity damping for motor 0x03.
    motor3_kd: float

    # MIT velocity damping for motor 0x04.
    motor4_kd: float


class BalanceController:
    """Generate wheel torque from pitch PID feedback."""

    def __init__(self, config: BalanceConfig | None = None):
        """Store the controller config and reset the integral state."""
        self.config = config or BalanceConfig()
        self.pitch_integral_deg_s = 0.0
        self._last_update_time: float | None = None

    def reset_integral(self) -> None:
        """Clear the pitch integral term."""
        self.pitch_integral_deg_s = 0.0
        self._last_update_time = None

    def update(
        self,
        pitch_deg: float,
        roll_deg: float,
        pitch_rate_deg_s: float = 0.0,
        dt_s: float | None = None,
    ) -> BalanceOutput:
        """Update PID control and return motor torque commands."""
        cfg = self.config
        pitch_error = pitch_deg - cfg.target_pitch_deg
        roll_error = roll_deg - cfg.target_roll_deg
        dt_s = self._resolve_dt(dt_s)
        self._update_pitch_integral(pitch_error, dt_s)

        # Sign convention: when pitch increases, motor 0x03 torque must be negative.
        motor3_tau = -(
            cfg.pitch_torque_kp * pitch_error
            + cfg.pitch_torque_ki * self.pitch_integral_deg_s
            + cfg.pitch_rate_torque_kd * pitch_rate_deg_s
        )
        motor3_tau = self._clamp(motor3_tau, cfg.max_wheel_torque)

        return BalanceOutput(
            pitch_error_deg=pitch_error,
            pitch_integral_deg_s=self.pitch_integral_deg_s,
            roll_error_deg=roll_error,
            target_q_rad=cfg.target_q_rad,
            motor3_tau=motor3_tau,
            motor4_tau=-motor3_tau,
        )

    def _resolve_dt(self, dt_s: float | None) -> float:
        """Resolve the integration step and ignore very long gaps."""
        now = time.monotonic()
        if dt_s is None:
            if self._last_update_time is None:
                dt_s = 0.0
            else:
                dt_s = now - self._last_update_time
        self._last_update_time = now
        if dt_s < 0.0 or dt_s > 0.2:
            return 0.0
        return dt_s

    def _update_pitch_integral(self, pitch_error: float, dt_s: float) -> None:
        """Accumulate and clamp the pitch integral term."""
        if self.config.pitch_torque_ki == 0.0:
            self.pitch_integral_deg_s = 0.0
            return

        self.pitch_integral_deg_s += pitch_error * dt_s
        self.pitch_integral_deg_s = self._clamp(
            self.pitch_integral_deg_s,
            self.config.pitch_integral_limit_deg_s,
        )

    @staticmethod
    def _clamp(value: float, limit: float) -> float:
        """Clamp a value to +/-limit."""
        abs_limit = abs(limit)
        return max(-abs_limit, min(abs_limit, value))


class RuntimeParameterManager:
    """Watch Balance.py and apply saved runtime parameters to the state machine."""

    def __init__(
        self,
        path: str | Path | None = None,
        reload_interval_s: float = 0.20,
    ):
        """Initialize the runtime parameter manager."""
        self.path = Path(__file__) if path is None else Path(path)
        self.reload_interval_s = reload_interval_s
        self.last_error: str | None = None
        self._last_check_time = 0.0
        self._last_mtime_ns = 0
        self.balance_gains = RuntimeBalanceGains(
            pitch_kp=float(BALANCE_PITCH_KP),
            pitch_ki=float(BALANCE_PITCH_KI),
            pitch_kd=float(BALANCE_PITCH_KD),
            wheel_kv=float(BALANCE_WHEEL_KV),
            motor3_kd=float(BALANCE_MOTOR3_KD),
            motor4_kd=float(BALANCE_MOTOR4_KD),
        )
        self.refresh(force=True)

    def apply_to_state_machine(self, state_machine, force: bool = False) -> bool:
        """Apply changed parameters to the state machine."""
        gains = self.refresh(force=force)
        if gains is None and not force:
            return False

        active_gains = self.balance_gains if gains is None else gains
        state_machine.set_balance_gains(
            pitch_kp=active_gains.pitch_kp,
            pitch_ki=active_gains.pitch_ki,
            pitch_kd=active_gains.pitch_kd,
            wheel_kv=active_gains.wheel_kv,
            motor3_kd=active_gains.motor3_kd,
            motor4_kd=active_gains.motor4_kd,
        )
        return gains is not None or force

    def refresh(self, force: bool = False) -> RuntimeBalanceGains | None:
        """Reload Balance.py when it has been saved."""
        now = time.monotonic()
        if not force and now - self._last_check_time < self.reload_interval_s:
            return None
        self._last_check_time = now

        try:
            mtime_ns = self.path.stat().st_mtime_ns
        except OSError as exc:
            self.last_error = f"cannot stat {self.path}: {exc}"
            return None

        if not force and mtime_ns == self._last_mtime_ns:
            return None

        try:
            gains = self._load_balance_gains()
        except Exception as exc:
            self.last_error = f"cannot load runtime params: {exc}"
            return None

        self._last_mtime_ns = mtime_ns
        self.last_error = None
        if not force and gains == self.balance_gains:
            return None

        self.balance_gains = gains
        return gains

    def _load_balance_gains(self) -> RuntimeBalanceGains:
        """Read the latest runtime gains from Balance.py on disk."""
        namespace = runpy.run_path(str(self.path))
        return RuntimeBalanceGains(
            pitch_kp=float(namespace.get("BALANCE_PITCH_KP", BALANCE_PITCH_KP)),
            pitch_ki=float(namespace.get("BALANCE_PITCH_KI", BALANCE_PITCH_KI)),
            pitch_kd=float(namespace.get("BALANCE_PITCH_KD", BALANCE_PITCH_KD)),
            wheel_kv=float(namespace.get("BALANCE_WHEEL_KV", BALANCE_WHEEL_KV)),
            motor3_kd=float(namespace.get("BALANCE_MOTOR3_KD", BALANCE_MOTOR3_KD)),
            motor4_kd=float(namespace.get("BALANCE_MOTOR4_KD", BALANCE_MOTOR4_KD)),
        )


# Default config used by the state machine.
DEFAULT_BALANCE_CONFIG = BalanceConfig()
